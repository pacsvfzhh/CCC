  v_count integer;
BEGIN
  INSERT INTO wallet_reconciliation_queue (
    user_id,
    requested_at,
    next_attempt_at,
    attempts,
    last_error
  )
  SELECT user_id, now(), now(), 0, NULL
  FROM wallets
  ON CONFLICT (user_id) DO UPDATE
  SET requested_at = EXCLUDED.requested_at,
      next_attempt_at = now(),
      attempts = 0,
      last_error = NULL;

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
