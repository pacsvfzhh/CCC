CREATE INDEX IF NOT EXISTS idx_wallet_reconciliation_queue_due
  ON wallet_reconciliation_queue (next_attempt_at, requested_at);
CREATE INDEX IF NOT EXISTS idx_wallet_reconciliation_audit_user
